import zipfile

from stable_datasets.schema import ClassLabel, DatasetInfo, DatasetSource, DownloadInfo, Features, Version
from stable_datasets.schema import Image as ImageFeature
from stable_datasets.utils import BaseDatasetBuilder


# The upstream repository is updated in place, so pin a commit (README version 2026.10.18.2).
_COMMIT = "18fbaa1b48a70d356e6aa47a8ff88156fb96b887"
_URL = f"https://github.com/fruits-360/fruits-360-100x100/archive/{_COMMIT}.zip"
_CHECKSUM = "sha256:50213ec3770a9f5dbceac91e8ca660b5507accb405ba89ac5fe9253b5597cadb"


class Fruits360(BaseDatasetBuilder):
    """Fruits-360: 100x100 images of fruits, vegetables, nuts, seeds and mushrooms.

    Each object was filmed while rotating on a slow motor in front of a white background, and the background
    was removed with a flood-fill algorithm. Different varieties of the same fruit are separate classes.
    The official Training/Test partitions are kept as released.
    """

    VERSION = Version("2026.10.18")

    SOURCE = DatasetSource(
        homepage="https://github.com/fruits-360",
        assets={
            "train": DownloadInfo(url=_URL, checksum=_CHECKSUM),
            "test": DownloadInfo(url=_URL, checksum=_CHECKSUM),
        },
        citation="""@article{muresan2018fruit,
                title   = {Fruit recognition from images using deep learning},
                author  = {Mure{\\c{s}}an, Horea and Oltean, Mihai},
                journal = {Acta Universitatis Sapientiae, Informatica},
                volume  = {10},
                number  = {1},
                pages   = {26--42},
                year    = {2018} }
        """,
    )

    _SPLIT_DIRS = {"train": "Training", "test": "Test"}

    def _info(self):
        return DatasetInfo(
            description="""Fruits-360 contains 100x100 RGB images of fruits, vegetables, nuts, seeds and mushrooms
                on a white background, across 274 classes where varieties of the same fruit are distinct classes.""",
            features=Features({"image": ImageFeature(), "label": ClassLabel(names=self._labels())}),
            supervised_keys=("image", "label"),
            homepage=self.SOURCE["homepage"],
            citation=self.SOURCE["citation"],
        )

    def _generate_examples(self, data_path, split):
        """Yield the JPEGs under ``<repo>/<Training|Test>/<class>/`` in the zip archive.

        Upstream has a few class folders that differ only in letter case (e.g. ``Blackberry 3`` and
        ``BlackBerry 3``) and hold disjoint images of the same class, so class names are matched
        case-insensitively. This gives the 274 classes reported by the dataset authors.
        """
        label_ids = {name.lower(): i for i, name in enumerate(self._labels())}
        split_dir = self._SPLIT_DIRS[split]
        with zipfile.ZipFile(data_path) as archive:
            for member in archive.infolist():
                parts = member.filename.split("/")
                if member.is_dir() or len(parts) != 4 or parts[1] != split_dir or not parts[3].endswith(".jpg"):
                    continue
                yield member.filename, {"image": archive.read(member), "label": label_ids[parts[2].lower()]}

