from PIL import Image as PILImage

from stable_datasets.schema import ClassLabel, DatasetInfo, DatasetSource, DownloadInfo, Features, Version
from stable_datasets.schema import Image as ImageFeature
from stable_datasets.utils import BaseDatasetBuilder


class Caltech256(BaseDatasetBuilder):
    """
    Caltech-256
    A collection of 30,607 training images with 256 categories and one additional clutter
    category (for testing background rejection) created by Griffin, Holub, and Perona (2007).
    Each category has a minimum of 80 images. There are 30,185 RGB and 422 grayscale images,
    all of which have been converted to contain 3 color channels, but the image sizes
    remain inconsistent.
    """

    VERSION = Version("1.0.0")

    SOURCE = DatasetSource(
        homepage="https://data.caltech.edu/records/nyy15-4j048",
        assets={
            "train": DownloadInfo(
                url="https://data.caltech.edu/records/nyy15-4j048/files/256_ObjectCategories.tar?download=1",
                checksum="md5:67b4f42ca05d46448c6bb8ecd2220f6d",
                filename="256_ObjectCategories.tar",
            ),
        },
        citation="""@article{griffin_holub_perona_2007,
                    title     = {Caltech-256 Object Category Dataset},
                    publisher = {California Institute of Technology},
                    author    = {Griffin, Gregory and Holub, Alex and Perona, Pietro},
                    year      = {2007},
                    month     = {mar}}""",
        license="Creative Commons Attribution 4.0 International",
    )

    def _info(self):
        """Returns information about the Caltech-256 dataset"""
        return DatasetInfo(
            features=Features(
                {
                    "image": ImageFeature(),
                    "label": ClassLabel(names=self._labels()),
                }
            ),
            description="Caltech-256 contains 256 object categories and an additional clutter category, for 30,607 images in total.",
            supervised_keys=("image", "label"),
            homepage=self.SOURCE["homepage"],
            citation=self.SOURCE["citation"],
            license=self.SOURCE["license"],
        )

    def _generate_examples(self, data_path, split):
        """Generate examples from the .tar archive."""
        with tarfile.open(data_path, "r") as tar:
            for member in tar:
                # check member type
                path = Path(member.name)
                if not member.isfile() or path.suffix != ".jpg":
                    continue

                # get label from path (e.g. "001.ak47/001_0001.jpg")
                label = path.parent.suffix[1:]

                # read image bytes
                with tar.extractfile(member) as f:
                    image_bytes = f.read()

                # ensure all images are RGB (lazy loading, only decodes if necessary)
                pil_image = PILImage.open(io.BytesIO(image_bytes))
                if pil_image.mode != "RGB":
                    image_bytes = ImageFeature().encode(pil_image.convert("RGB"))

                # yield training example, using path as key for traceability
                key = str(path.relative_to(path.parents[1]))
                yield key, {"image": image_bytes, "label": label}

